function initExam() {
    // Load currently selected paragraph array
    selectedMatterIndex = parseInt(matterSelect.value) || 0;
    sourceWords = legalMattersList[selectedMatterIndex].trim().split(/\s+/).slice(0, 350);

    textPanel.innerHTML = '';
    sourceWords.forEach((word, idx) => {
        const span = document.createElement('span');
        span.innerText = word;
        span.className = 'word';
        span.id = `word-${idx}`;
        textPanel.appendChild(span);
    });
    
    if (sourceWords.length > 0) {
        document.getElementById('word-0').classList.add('current-word');
    }
    
    backspaceCount = 0;
    wrongWordsCount = 0;
    currentWordIndex = 0;
    
    clearInterval(countdownInterval);
    timeLeft = EXAM_DURATION;
    isTestStarted = false;
    if (timerDisplay) timerDisplay.classList.remove('timer-warning');
    formatTimeDisplay(timeLeft);
    
    typingArea.value = '';
    typingArea.disabled = false;
    typingArea.placeholder = "अपने सिस्टम पर Remington Gail कीबोर्ड चालू करें और यहाँ टाइप करना शुरू करें...";
    
    updateScoreboard();
    loadHistoryTable();
}

function startTimer() {
    isTestStarted = true;
    countdownInterval = setInterval(() => {
        timeLeft--;
        formatTimeDisplay(timeLeft);
        updateScoreboard();
        
        if (timeLeft <= 60 && timerDisplay) {
            timerDisplay.classList.add('timer-warning');
        }
        if (timeLeft <= 0) {
            endExam("समय समाप्त! (Time's Up!)");
        }
    }, 1000);
}

function formatTimeDisplay(seconds) {
    if (!timerDisplay) return;
    const mins = Math.floor(seconds / 60);
    const secs = seconds % 60;
    timerDisplay.innerText = `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
}

typingArea.addEventListener('keydown', (e) => {
    if (typingArea.disabled) return;
    if (!isTestStarted) startTimer();

    if (e.key === 'Backspace') {
        backspaceCount++;
        updateScoreboard();
    }
});

